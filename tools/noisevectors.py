#!/usr/bin/env python3
"""Writes src/shared/noisevectors.h from tests/noise/xk-vectors.json (Noise test vectors for
Noise_XK_25519_ChaChaPoly_BLAKE2b). Run from the repo root after changing the JSON file."""
import json

FIELDS = ["init_prologue", "init_static", "init_ephemeral", "init_remote_static",
          "resp_prologue", "resp_static", "resp_ephemeral"]

vectors = json.load(open("tests/noise/xk-vectors.json"))["vectors"]
out = ["// Generated by tools/noisevectors.py from tests/noise/xk-vectors.json; do not edit.", ""]
out.append("struct noisevector")
out.append("{")
for f in FIELDS + ["handshake_hash"]:
    out.append("    const char *%s;" % f)
out.append("    int messages;")
out.append("    const char *payload[8], *ciphertext[8];")
out.append("};")
out.append("")
out.append("static const noisevector noisevectors[] =")
out.append("{")
for v in vectors:
    msgs = v["messages"]
    assert len(msgs) <= 8
    fields = ", ".join('"%s"' % v[f] for f in FIELDS)
    hh = '"%s"' % v.get("handshake_hash", "")
    payloads = ", ".join('"%s"' % m["payload"] for m in msgs)
    cts = ", ".join('"%s"' % m["ciphertext"] for m in msgs)
    out.append("    { %s, %s, %d, { %s }, { %s } }," % (fields, hh, len(msgs), payloads, cts))
out.append("};")
open("src/shared/noisevectors.h", "w").write("\n".join(out) + "\n")
print("wrote %d vectors" % len(vectors))
