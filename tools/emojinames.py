#!/usr/bin/env python3
# emojinames.py <gemoji db/emoji.json> > server/discord/emojinames.go && gofmt -w server/discord/emojinames.go
# Builds the Discord reader's emoji -> short name table from GitHub's gemoji (MIT licence).
import json, sys

def goquote(s):
    return '"' + ''.join(c if 0x20 <= ord(c) < 0x7f and c not in '"\\' else ('\\U%08X' % ord(c) if ord(c) > 0xFFFF else '\\u%04X' % ord(c)) for c in s) + '"'

d = json.load(open(sys.argv[1]))
rows = {}
for e in d:
    key = e['emoji'].replace('️', '')
    if all(ord(c) < 0x2000 for c in key) or 0x1F1E6 <= ord(key[0]) <= 0x1F1FF:
        continue
    names = [a for a in e['aliases'] if a[0].isalpha()] or e['aliases']
    rows[key] = names[0]
print('// Code generated by tools/emojinames.py from GitHub\'s gemoji (db/emoji.json, MIT licence,')
print('// Copyright (c) 2019 GitHub, Inc.). DO NOT EDIT.')
print()
print('package discord')
print()
print('// emojiNames maps an emoji, without variation selectors and skin tones, to its short name')
print('var emojiNames = map[string]string{')
for k in sorted(rows):
    print(f'\t{goquote(k)}: {goquote(rows[k])},')
print('}')
